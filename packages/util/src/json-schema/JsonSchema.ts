import type { ExtendedJSONSchema, JSONSchemaExtension } from "@sroussey/json-schema-to-ts";

export type JsonSchemaCustomProps = {
  "x-replicate"?: boolean;
  "x-ui-reactive"?: boolean | string; // hint that this field responds to reactive changes
  "x-ui-hidden"?: boolean;
  "x-ui-order"?: number;
  "x-ui-priority"?: number;
  "x-ui-viewer"?: string;
  "x-ui-type-override"?: boolean;
  "x-ui-editor"?: string;
  "x-ui-group"?: string;
  "x-ui-group-order"?: number;
  "x-ui-group-priority"?: number;
  "x-ui-group-open"?: boolean;
  "x-ui-enum-labels"?: Record<string, string>; // Map of enum value -> display label
  "x-ui-placeholder"?: string; // placeholder shown by the editor while the field holds no value
  "x-ui-disabled"?: boolean; // renders the field read-only (the value is shown but cannot be edited)
  "x-ui-manual"?: boolean; // marks a property as manually added by the user
  "x-ui"?: unknown;
  "x-ui-iteration"?: boolean; // marks property as iteration-injected (hidden from parent, read-only in subgraph)
  "x-auto-generated"?: boolean; // marks a primary key column as auto-generated by storage backend
  "x-stream"?: "append" | "replace" | "object" | "binary"; // streaming mode for this port (absent = none/non-streaming)
  "x-structured-output"?: boolean; // marks a port as requiring structured output from the AI provider
};

export type JsonSchema<EXTENSION extends JSONSchemaExtension = JsonSchemaCustomProps> =
  ExtendedJSONSchema<EXTENSION>;
