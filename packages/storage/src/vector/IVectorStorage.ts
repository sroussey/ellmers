export type AnyVectorStorage = Omit<
  IVectorStorage<any, any, any, any>,
  "queryIndex" | "withTransaction"
> & {
  queryIndex(criteria: any, options: any): Promise<any[]>;
  withTransaction<T>(fn: (tx: any) => Promise<T>): Promise<T>;
};

/**
 * Distance metric used by vector indexes.
 *
 * - `cosine`: cosine distance (1 - cosine similarity). Default for embedding
 *   models that produce normalised vectors. Recommended starting point for
 *   text/RAG workloads.
 * - `l2`: euclidean distance. Use when vectors carry magnitude information.
 * - `ip`: negative inner product. Use when embeddings are pre-normalised AND
 *   you want a slightly cheaper similarity computation than cosine.
 */
export type VectorDistanceMetric = "cosine" | "l2" | "ip";

/**
 * HNSW index parameters. HNSW is the default approximate-nearest-neighbour
 * algorithm in pgvector and other modern vector indexes; tuning these knobs
 * trades index build cost and memory for recall and query latency.
 *
 * Defaults from pgvector when unspecified: `m = 16`, `efConstruction = 64`,
 * `efSearch = 40`.
 *
 * - `m`: number of bi-directional links per layer. Higher = better recall,
 *   more memory, slower build. Typical values: 8 (low-recall), 16 (default),
 *   32 (high-recall).
 * - `efConstruction`: candidate-list size during index build. Higher = better
 *   recall, much slower build. Typical values: 64 (default), 200, 400.
 * - `efSearch`: candidate-list size at query time. Higher = better recall,
 *   slower queries. Typical values: 40 (default), 80, 200. This is the knob
 *   you want to tune at query time once the index is built.
 */
export interface HnswIndexOptions {
  readonly m?: number;
  readonly efConstruction?: number;
  readonly efSearch?: number;
}

/**
 * IVFFlat index parameters (pgvector). Offers faster builds than HNSW at the
 * cost of recall, useful for very large corpora.
 *
 * - `lists`: number of inverted lists. pgvector docs recommend `rows / 1000`
 *   for up to 1M rows, then `sqrt(rows)` for larger sets.
 * - `probes`: number of lists scanned at query time. Higher = better recall,
 *   slower queries. Default `1`.
 */
export interface IvfflatIndexOptions {
  readonly lists: number;
  readonly probes?: number;
}

/**
 * Vector-index tuning options threaded into the storage constructor and
 * applied during {@link IVectorStorage} setup / migration.
 *
 * Only one of `hnsw` or `ivfflat` should be set; if both are absent the
 * backend uses a sensible default (HNSW on pgvector, COSINE-only for
 * sqlite-vec which does not yet support HNSW tuning).
 */
export interface VectorIndexOptions {
  readonly distance?: VectorDistanceMetric;
  readonly hnsw?: HnswIndexOptions;
  readonly ivfflat?: IvfflatIndexOptions;
}

/**
 * Options for vector search operations
 */
export interface VectorSearchOptions<
  Metadata extends Record<string, unknown> | undefined = Record<string, unknown>,
> {
  readonly topK?: number;
  readonly filter?: Partial<Metadata>;
  readonly scoreThreshold?: number;
}

/**
 * Options for hybrid search (vector + full-text)
 */
export interface HybridSearchOptions<
  Metadata extends Record<string, unknown> | undefined = Record<string, unknown>,
> extends VectorSearchOptions<Metadata> {
  readonly textQuery: string;
  readonly vectorWeight?: number;
}

/**
 * Type definitions for document chunk vector repository events
 */
export interface VectorEventListeners<PrimaryKey, Entity> extends TabularEventListeners<
  PrimaryKey,
  Entity
> {
  similaritySearch: (query: TypedArray, results: (Entity & { score: number })[]) => void;
  hybridSearch: (query: TypedArray, results: (Entity & { score: number })[]) => void;
}

export type VectorEventName = keyof VectorEventListeners<any, any>;
export type VectorEventListener<
  Event extends VectorEventName,
  PrimaryKey,
  Entity,
> = VectorEventListeners<PrimaryKey, Entity>[Event];

export type VectorEventParameters<
  Event extends VectorEventName,
  PrimaryKey,
  Entity,
> = EventParameters<VectorEventListeners<PrimaryKey, Entity>, Event>;

/**
 * Interface defining the contract for vector storage repositories.
 * These repositories store vector embeddings with metadata.
 * Extends ITabularStorage to provide standard storage operations,
 * plus vector-specific similarity search capabilities.
 * Supports various vector types including quantized formats.
 *
 * @typeParam Schema - The schema definition for the entity using JSON Schema
 * @typeParam PrimaryKeyNames - Array of property names that form the primary key
 * @typeParam Entity - The entity type
 */
export interface IVectorStorage<
  Metadata extends Record<string, unknown> | undefined,
  Schema extends DataPortSchemaObject,
  Entity = FromSchema<Schema, TypedArraySchemaOptions>,
  PrimaryKeyNames extends ReadonlyArray<keyof Schema["properties"]> = ReadonlyArray<
    keyof Schema["properties"]
  >,
  PrimaryKey = SimplifyPrimaryKey<Entity, PrimaryKeyNames>,
  InsertType = InsertEntity<Entity, AutoGeneratedKeys<Schema>>,
> extends ITabularStorage<Schema, PrimaryKeyNames, Entity, PrimaryKey, InsertType> {
  /**
   * Get the vector dimension
   * @returns The vector dimension
   */
  getVectorDimensions(): number;

  /**
   * Search for similar vectors using similarity scoring
   * @param query - Query vector to compare against
   * @param options - Search options (topK, filter, scoreThreshold)
   * @returns Array of search results sorted by similarity (highest first)
   */
  similaritySearch(
    query: TypedArray,
    options?: VectorSearchOptions<Metadata>
  ): Promise<(Entity & { score: number })[]>;

  /**
   * Hybrid search combining vector similarity with full-text search
   * This is optional and may not be supported by all implementations
   * @param query - Query vector to compare against
   * @param options - Hybrid search options including text query
   * @returns Array of search results sorted by combined relevance
   */
  hybridSearch?(
    query: TypedArray,
    options: HybridSearchOptions<Metadata>
  ): Promise<(Entity & { score: number })[]>;
}

/**
 * TODO: Given a schema, return the vector column by searching for a property with a TypedArray format (or TypedArray:xxx format)
 */

export function getVectorProperty<Schema extends DataPortSchemaObject>(
  schema: Schema
): keyof Schema["properties"] | undefined {
  for (const [key, value] of Object.entries<JsonSchema>(schema.properties)) {
    if (
      typeof value !== "boolean" &&
      value.type === "array" &&
      (value.format === "TypedArray" || value.format?.startsWith("TypedArray:"))
    ) {
      return key;
    }
  }
  return undefined;
}

/**
 * Given a schema, return the property which is an object with format "metadata"
 */
export function getMetadataProperty<Schema extends DataPortSchemaObject>(
  schema: Schema
): keyof Schema["properties"] | undefined {
  for (const [key, value] of Object.entries<JsonSchema>(schema.properties)) {
    if (typeof value !== "boolean" && value.type === "object" && value.format === "metadata") {
      return key;
    }
  }
  return undefined;
}
