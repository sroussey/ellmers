  /**
   * Determines the generation strategy for an auto-generated key based on its type
   * @param columnName - Name of the column
   * @param typeDef - JSON Schema type definition for the column
   * @returns The generation strategy to use
   */
  protected determineGenerationStrategy(columnName: string, typeDef: any): KeyGenerationStrategy {
    // Extract the actual type if it's a union with null
    let actualType = typeDef;
    if (typeDef && typeof typeDef === "object") {
      if (typeDef.anyOf && Array.isArray(typeDef.anyOf)) {
        actualType = typeDef.anyOf.find((t: any) => t.type !== "null") || typeDef;
      } else if (typeDef.oneOf && Array.isArray(typeDef.oneOf)) {
        actualType = typeDef.oneOf.find((t: any) => t.type !== "null") || typeDef;
      }
    }

    if (typeof actualType !== "object") {
      return "uuid";
    }

    // Integer types use autoincrement
    if (actualType.type === "integer") {
      return "autoincrement";
    }

    // Default to UUID for strings and other types
    return "uuid";
  }

