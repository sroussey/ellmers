import { InMemoryTabularStorage } from "@workglow/storage";
import { setLogger } from "@workglow/util";
import { describe, expect, it } from "vitest";
import { getTestingLogger } from "../../binding/TestingLogger";
import { runGenericTabularStorageSubscriptionTests } from "./genericTabularStorageSubscriptionTests";
import {
  AllTypesPrimaryKeyNames,
  AllTypesSchema,
  AutoIncrementPrimaryKeyNames,
  AutoIncrementSchema,
  CompoundPrimaryKeyNames,
  CompoundSchema,
  runAutoGeneratedKeyTests,
  runGenericTabularStorageTests,
  SearchPrimaryKeyNames,
  SearchSchema,
  UuidPrimaryKeyNames,
  UuidSchema,
} from "./genericTabularStorageTests";

describe("InMemoryTabularStorage", () => {
  let logger = getTestingLogger();
  setLogger(logger);
  runGenericTabularStorageTests(
    async () =>
      new InMemoryTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
        CompoundSchema,
        CompoundPrimaryKeyNames
      ),
    async () =>
      new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
        SearchSchema,
        SearchPrimaryKeyNames,
        ["category", ["category", "subcategory"], ["subcategory", "category"], "value"]
      ),
    async () =>
      new InMemoryTabularStorage<typeof AllTypesSchema, typeof AllTypesPrimaryKeyNames>(
        AllTypesSchema,
        AllTypesPrimaryKeyNames
      )
  );

  runGenericTabularStorageSubscriptionTests(
    async () =>
      new InMemoryTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
        CompoundSchema,
        CompoundPrimaryKeyNames
      ),
    { usesPolling: false }
  );

  runAutoGeneratedKeyTests(
    async () =>
      new InMemoryTabularStorage<typeof AutoIncrementSchema, typeof AutoIncrementPrimaryKeyNames>(
        AutoIncrementSchema,
        AutoIncrementPrimaryKeyNames
      ),
    async () =>
      new InMemoryTabularStorage<typeof UuidSchema, typeof UuidPrimaryKeyNames>(
        UuidSchema,
        UuidPrimaryKeyNames
      )
  );
});

describe("InMemoryTabularStorage.queryIndex", () => {
  it("returns projected rows containing only requested columns", async () => {
    const storage = new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category", "subcategory"]]
    );
    await storage.put({
      id: "k1",
      category: "a",
      subcategory: "x",
      value: 1,
      createdAt: "2025-01-01T00:00:00Z",
      updatedAt: "2025-01-01T00:00:00Z",
    });
    const rows = await storage.queryIndex(
      { category: "a" },
      { select: ["id", "category"], orderBy: [{ column: "subcategory", direction: "ASC" }] }
    );
    expect(rows).toHaveLength(1);
    expect(Object.keys(rows[0]).sort()).toEqual(["category", "id"]);
    expect((rows[0] as any).value).toBeUndefined();
  });

  it("throws CoveringIndexMissingError when no covering index exists", async () => {
    const storage = new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category"]]
    );
    await expect(
      storage.queryIndex(
        { value: 1 },
        { select: ["id"] }
      )
    ).rejects.toThrow(/CoveringIndexMissingError|No covering index/);
  });

  it("returns empty array (not undefined) on no matches", async () => {
    const storage = new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category"]]
    );
    const rows = await storage.queryIndex(
      { category: "missing" },
      { select: ["id"] }
    );
    expect(rows).toEqual([]);
  });

  it("throws StorageValidationError on empty select array", async () => {
    const storage = new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category"]]
    );
    await expect(
      storage.queryIndex({ category: "a" }, { select: [] as any })
    ).rejects.toThrow(/non-empty select/);
  });

  it("throws StorageValidationError when select contains a column not in schema", async () => {
    const storage = new InMemoryTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category"]]
    );
    await expect(
      storage.queryIndex({ category: "a" }, { select: ["nonexistentCol"] as any })
    ).rejects.toThrow(/not in schema/);
  });
});
