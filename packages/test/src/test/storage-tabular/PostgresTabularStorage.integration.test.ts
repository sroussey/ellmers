import { PGlite } from "@electric-sql/pglite";
import { PostgresTabularStorage } from "@workglow/postgres/storage";
import { setLogger, uuid4 } from "@workglow/util";
import type { Pool } from "pg";
import { afterAll, describe, expect, it } from "vitest";
import { getTestingLogger } from "../../binding/TestingLogger";
import {
  AllTypesPrimaryKeyNames,
  AllTypesSchema,
  AutoIncrementPrimaryKeyNames,
  AutoIncrementSchema,
  CompoundPrimaryKeyNames,
  CompoundSchema,
  runAutoGeneratedKeyTests,
  runGenericTabularStorageTests,
  SearchPrimaryKeyNames,
  SearchSchema,
  UuidPrimaryKeyNames,
  UuidSchema,
} from "./genericTabularStorageTests";

const db = new PGlite() as unknown as Pool;

describe("PostgresTabularStorage", () => {
  let logger = getTestingLogger();
  setLogger(logger);

  afterAll(async () => {
    await (db as unknown as PGlite).close();
  });

  runGenericTabularStorageTests(
    async () =>
      new PostgresTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
        db,
        `sql_test_${uuid4().replace(/-/g, "_")}`,
        CompoundSchema,
        CompoundPrimaryKeyNames
      ),
    async () =>
      new PostgresTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
        db,
        `sql_test_${uuid4().replace(/-/g, "_")}`,
        SearchSchema,
        SearchPrimaryKeyNames,
        ["category", ["category", "subcategory"], ["subcategory", "category"], "value"]
      ),
    async () => {
      const repo = new PostgresTabularStorage<
        typeof AllTypesSchema,
        typeof AllTypesPrimaryKeyNames
      >(
        db,
        `all_types_test_${uuid4().replace(/-/g, "_")}`,
        AllTypesSchema,
        AllTypesPrimaryKeyNames
      );
      await repo.setupDatabase();
      return repo;
    }
  );

  runAutoGeneratedKeyTests(
    async () =>
      new PostgresTabularStorage<typeof AutoIncrementSchema, typeof AutoIncrementPrimaryKeyNames>(
        db,
        `autoinc_test_${uuid4().replace(/-/g, "_")}`,
        AutoIncrementSchema,
        AutoIncrementPrimaryKeyNames
      ),
    async () =>
      new PostgresTabularStorage<typeof UuidSchema, typeof UuidPrimaryKeyNames>(
        db,
        `uuid_test_${uuid4().replace(/-/g, "_")}`,
        UuidSchema,
        UuidPrimaryKeyNames
      )
  );

  describe("withTransaction", () => {
    it("rolls back all writes when the callback throws", async () => {
      const storage = new PostgresTabularStorage<
        typeof CompoundSchema,
        typeof CompoundPrimaryKeyNames
      >(
        db,
        `tx_test_${uuid4().replace(/-/g, "_")}`,
        CompoundSchema,
        CompoundPrimaryKeyNames
      );
      await storage.setupDatabase();

      await expect(
        storage.withTransaction(async (tx) => {
          await tx.put({ name: "a", type: "x", option: "v1", success: true });
          await tx.put({ name: "b", type: "x", option: "v2", success: true });
          throw new Error("boom");
        })
      ).rejects.toThrow("boom");

      expect(await storage.get({ name: "a", type: "x" })).toBeUndefined();
      expect(await storage.get({ name: "b", type: "x" })).toBeUndefined();
    });
  });
});
