describe("DuckDbTabularStorage regressions", () => {
  const JunctionSchema = {
    type: "object",
    properties: { a: { type: "string" }, b: { type: "string" } },
    required: ["a", "b"],
    additionalProperties: false,
  } as const satisfies DataPortSchemaObject;

  const tempDir = mkdtempSync(join(tmpdir(), "duckdb-test-"));
  afterAll(() => {
    rmSync(tempDir, { recursive: true, force: true });
  });

  it("re-put of an existing row on an all-primary-key table is an upsert, not an error", async () => {
    const storage = new DuckDbTabularStorage<typeof JunctionSchema, readonly ["a", "b"]>(
      ":memory:",
      "junction",
      JunctionSchema,
      ["a", "b"] as const
    );
    await storage.setupDatabase();
    await storage.put({ a: "x", b: "y" });
    const again = await storage.put({ a: "x", b: "y" });
    expect(again).toEqual({ a: "x", b: "y" });
    expect(await storage.size()).toBe(1);
  });

  it("putBulk re-put of an existing row on an all-primary-key table is an upsert, not an error", async () => {
    const storage = new DuckDbTabularStorage<typeof JunctionSchema, readonly ["a", "b"]>(
      ":memory:",
      "junction_bulk",
      JunctionSchema,
      ["a", "b"] as const
    );
    await storage.setupDatabase();
    await storage.putBulk([{ a: "x", b: "y" }]);
    const again = await storage.putBulk([{ a: "x", b: "y" }]);
    expect(again).toEqual([{ a: "x", b: "y" }]);
    expect(await storage.size()).toBe(1);
  });

  it("two storages opened with the same file path share one database", async () => {
    const path = join(tempDir, "shared.duckdb");
    const s1 = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      path,
      "shared_tbl",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    const s2 = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      path,
      "shared_tbl",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await s1.setupDatabase();
    await s2.setupDatabase();
    await s1.put({ name: "k", type: "t", option: "v", success: true });
    const seen = await s2.get({ name: "k", type: "t" });
    expect(seen?.option).toBe("v");
    s1.destroy();
    s2.destroy();
  });

  it("a sibling same-path storage's transaction does not roll back this storage's writes", async () => {
    const path = join(tempDir, "tx-isolated.duckdb");
    const a = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      path,
      "iso_a",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    const b = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      path,
      "iso_b",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await a.setupDatabase();
    await b.setupDatabase();

    let release: () => void = () => {};
    const gate = new Promise<void>((resolve) => {
      release = resolve;
    });
    const txPromise = a.withTransaction(async (tx) => {
      await tx.put({ name: "a-row", type: "t", option: "tx", success: true });
      await gate;
      throw new Error("rollback");
    });
    await Promise.resolve();
    await b.put({ name: "b-row", type: "t", option: "independent", success: true });
    release();
    await expect(txPromise).rejects.toThrow("rollback");

    expect(await a.get({ name: "a-row", type: "t" })).toBeUndefined();
    const bRow = await b.get({ name: "b-row", type: "t" });
    expect(bRow?.option).toBe("independent");
    a.destroy();
    b.destroy();
  });

  it("a write deferred during its own instance's transaction still takes the connection chain", async () => {
    // Scripted stub instead of a real database: exec/query log their SQL and
    // the first INSERT stalls until released, so cross-instance ordering is
    // asserted at the statement level with no timing races.
    const log: string[] = [];
    let releaseInsert: () => void = () => {};
    const stubDb = {
      exec: async (sql: string) => {
        log.push(sql);
      },
      query: async (sql: string) => {
        log.push(sql);
        if (sql.trimStart().startsWith("INSERT")) {
          await new Promise<void>((resolve) => {
            releaseInsert = resolve;
          });
        }
        return { rows: [{ a: "x", b: "y" }] };
      },
    };
    const settle = async () => {
      for (let i = 0; i < 5; i++) await new Promise((resolve) => setImmediate(resolve));
    };
    const a = new DuckDbTabularStorage<typeof JunctionSchema, readonly ["a", "b"]>(
      stubDb as any,
      "chain_a",
      JunctionSchema,
      ["a", "b"] as const
    );
    const b = new DuckDbTabularStorage<typeof JunctionSchema, readonly ["a", "b"]>(
      stubDb as any,
      "chain_b",
      JunctionSchema,
      ["a", "b"] as const
    );

    let openTx: () => void = () => {};
    const gate = new Promise<void>((resolve) => {
      openTx = resolve;
    });
    const tx = a.withTransaction(async () => {
      await gate;
    });
    await settle();

    // Issued while a's transaction is open: the write must queue on the shared
    // connection chain, not merely on a's instance mutex — a mutex-only wait
    // would wake after COMMIT and run with no chain slot, free to interleave
    // into a sibling's next BEGIN/COMMIT.
    const put = a.put({ a: "x", b: "y" });
    await settle();
    openTx();
    await tx;
    // a's deferred put now holds the chain slot with its INSERT in flight.
    await settle();

    const txB = b.withTransaction(async () => {});
    await settle();
    expect(log.filter((sql) => sql === "BEGIN")).toHaveLength(1);

    releaseInsert();
    await Promise.all([put, txB]);
    const relevant = log
      .filter((sql) => sql === "BEGIN" || sql === "COMMIT" || sql.trimStart().startsWith("INSERT"))
      .map((sql) => (sql.trimStart().startsWith("INSERT") ? "INSERT" : sql));
    expect(relevant).toEqual(["BEGIN", "COMMIT", "INSERT", "BEGIN", "COMMIT"]);
  });

  it("tx.updateWhere enforces the primary-key immutability guard", async () => {
    const storage = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      "pk_guard",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    await storage.put({ name: "n", type: "t", option: "v", success: true });
    await expect(
      storage.withTransaction(async (tx) => {
        await tx.updateWhere({ option: "v" }, { name: "renamed" } as any);
      })
    ).rejects.toThrow();
    expect((await storage.get({ name: "n", type: "t" }))?.option).toBe("v");
  });

  it("tx.getBulk with an empty key list returns [] instead of emitting IN ()", async () => {
    const storage = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      "empty_bulk",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    const rows = await storage.withTransaction(async (tx) => tx.getBulk([]));
    expect(rows).toEqual([]);
  });

  it("tx.getPage without a request object uses the default page request", async () => {
    const storage = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      "page_default",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    await storage.put({ name: "p", type: "t", option: "v", success: true });
    const page = await storage.withTransaction(async (tx) => tx.getPage());
    expect(page.items).toHaveLength(1);
  });

  it("put({}) works for a schema whose only column is an auto-generated key", async () => {
    const IdOnlySchema = {
      type: "object",
      properties: {
        id: { type: "integer", "x-auto-generated": true },
      },
      required: ["id"],
      additionalProperties: false,
    } as const satisfies DataPortSchemaObject;
    const storage = new DuckDbTabularStorage<typeof IdOnlySchema, readonly ["id"]>(
      ":memory:",
      "id_only",
      IdOnlySchema,
      ["id"] as const
    );
    await storage.setupDatabase();
    const first = await storage.put({} as any);
    const second = await storage.put({} as any);
    expect(typeof first.id).toBe("number");
    expect(second.id).toBeGreaterThan(first.id);
  });

  it("rejects negative values for columns declared with minimum 0", async () => {
    const UnsignedSchema = {
      type: "object",
      properties: {
        id: { type: "string" },
        count: { type: "integer", minimum: 0 },
      },
      required: ["id", "count"],
      additionalProperties: false,
    } as const satisfies DataPortSchemaObject;
    const storage = new DuckDbTabularStorage<typeof UnsignedSchema, readonly ["id"]>(
      ":memory:",
      "unsigned_check",
      UnsignedSchema,
      ["id"] as const
    );
    await storage.setupDatabase();
    await storage.put({ id: "ok", count: 5 });
    await expect(storage.put({ id: "bad", count: -5 })).rejects.toThrow(/CHECK/i);
  });

  it("a put listener can start a follow-up transaction from the post-commit event flush", async () => {
    const storage = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      "flush_order",
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    let followUp: Promise<unknown> | undefined;
    storage.on("put", (entity) => {
      if (entity.name === "first") {
        followUp = storage.withTransaction(async (tx) => {
          await tx.put({ name: "second", type: "t", option: "v", success: true });
        });
      }
    });
    await storage.withTransaction(async (tx) => {
      await tx.put({ name: "first", type: "t", option: "v", success: true });
    });
    expect(followUp).toBeDefined();
    await followUp;
    expect(await storage.get({ name: "second", type: "t" })).toBeDefined();
  });
});

describe("DuckDbTabularStorage.withTransaction", () => {
  async function makeStorage() {
    const storage = new DuckDbTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      `tx_test_${uuid4().replace(/-/g, "_")}`,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    return storage;
  }

  it("rolls back all writes when the callback throws", async () => {
    const storage = await makeStorage();

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "a", type: "x", option: "v1", success: true });
        await tx.put({ name: "b", type: "x", option: "v2", success: true });
        throw new Error("boom");
      })
    ).rejects.toThrow("boom");

    expect(await storage.get({ name: "a", type: "x" })).toBeUndefined();
    expect(await storage.get({ name: "b", type: "x" })).toBeUndefined();
  });

  it("rejects nested withTransaction calls instead of corrupting the outer transaction", async () => {
    const storage = await makeStorage();

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "outer", type: "x", option: "v", success: true });
        await tx.withTransaction(async () => {
          // unreachable
        });
      })
    ).rejects.toThrow(/does not support nesting/);

    // Outer transaction was rolled back as a result of the nested-call error.
    expect(await storage.get({ name: "outer", type: "x" })).toBeUndefined();
  });

  it("defers put events until COMMIT and discards them on ROLLBACK", async () => {
    const storage = await makeStorage();
    const observed: string[] = [];
    storage.on("put", (entity) => observed.push(entity.name));

    await storage.withTransaction(async (tx) => {
      await tx.put({ name: "committed", type: "x", option: "v", success: true });
      // No events should have been observed yet
      expect(observed).toEqual([]);
    });
    expect(observed).toEqual(["committed"]);

    observed.length = 0;

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "doomed", type: "x", option: "v", success: true });
        throw new Error("rollback");
      })
    ).rejects.toThrow("rollback");

    // The doomed put should never have been observed by listeners.
    expect(observed).toEqual([]);
  });

  it("serializes external put() calls behind a running withTransaction (rollback case)", async () => {
    // The concurrency contract: while withTransaction is awaiting its callback,
    // an unrelated `storage.put()` invoked from outside `fn` must NOT slip into
    // the open transaction. The mutex enforces this — the external put queues
    // until COMMIT/ROLLBACK releases the lock.
    const storage = await makeStorage();

    let releaseInner: () => void = () => {};
    const innerCanFinish = new Promise<void>((resolve) => {
      releaseInner = resolve;
    });

    const txPromise = storage.withTransaction(async (tx) => {
      await tx.put({ name: "tx-row", type: "x", option: "tx", success: true });
      // Hold the transaction open until the external caller has been queued.
      await innerCanFinish;
      throw new Error("rollback");
    });

    // Yield enough microtasks for the external put() to observe withTransaction's mutex hold.
    await Promise.resolve();
    await Promise.resolve();

    const externalPut = storage.put({
      name: "external-row",
      type: "x",
      option: "external",
      success: true,
    });

    // Let the inner callback throw, triggering ROLLBACK.
    releaseInner();
    await expect(txPromise).rejects.toThrow("rollback");

    // External put runs *after* ROLLBACK and is its own committed write.
    await externalPut;

    // tx-row was rolled back, external-row was committed independently.
    expect(await storage.get({ name: "tx-row", type: "x" })).toBeUndefined();
    const ext = await storage.get({ name: "external-row", type: "x" });
    expect(ext?.option).toEqual("external");
  });
});
