describe("SqliteTabularStorage.queryIndex", () => {
  it("returns projected rows containing only requested columns", async () => {
    const storage = new SqliteTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      ":memory:",
      "test_queryindex",
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category", "subcategory"]]
    );
    await storage.setupDatabase();
    await storage.put({
      id: "k1",
      category: "a",
      subcategory: "x",
      value: 1,
      createdAt: "2025-01-01T00:00:00Z",
      updatedAt: "2025-01-01T00:00:00Z",
    });
    const rows = await storage.queryIndex(
      { category: "a" },
      { select: ["id", "category"], orderBy: [{ column: "subcategory", direction: "ASC" }] }
    );
    expect(rows).toHaveLength(1);
    expect(Object.keys(rows[0]).sort()).toEqual(["category", "id"]);
    expect((rows[0] as any).value).toBeUndefined();
  });

  it("throws CoveringIndexMissingError when no covering index exists", async () => {
    const storage = new SqliteTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      ":memory:",
      "test_queryindex_noindex",
      SearchSchema,
      SearchPrimaryKeyNames,
      []
    );
    await storage.setupDatabase();
    await expect(storage.queryIndex({ category: "a" }, { select: ["id"] })).rejects.toThrow(
      /CoveringIndexMissingError|No covering index/
    );
  });

  it("returns empty array (not undefined) on no matches", async () => {
    const storage = new SqliteTabularStorage<typeof SearchSchema, typeof SearchPrimaryKeyNames>(
      ":memory:",
      "test_queryindex_empty",
      SearchSchema,
      SearchPrimaryKeyNames,
      [["category"]]
    );
    await storage.setupDatabase();
    const rows = await storage.queryIndex({ category: "missing" }, { select: ["id"] });
    expect(rows).toEqual([]);
  });
});

describe("SqliteTabularStorage.withTransaction", () => {
  async function makeStorage() {
    const storage = new SqliteTabularStorage<typeof CompoundSchema, typeof CompoundPrimaryKeyNames>(
      ":memory:",
      `tx_test_${uuid4().replace(/-/g, "_")}`,
      CompoundSchema,
      CompoundPrimaryKeyNames
    );
    await storage.setupDatabase();
    return storage;
  }

  it("rolls back all writes when the callback throws", async () => {
    const storage = await makeStorage();

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "a", type: "x", option: "v1", success: true });
        await tx.put({ name: "b", type: "x", option: "v2", success: true });
        throw new Error("boom");
      })
    ).rejects.toThrow("boom");

    expect(await storage.get({ name: "a", type: "x" })).toBeUndefined();
    expect(await storage.get({ name: "b", type: "x" })).toBeUndefined();
  });

  it("rejects nested withTransaction calls instead of corrupting the outer transaction", async () => {
    const storage = await makeStorage();

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "outer", type: "x", option: "v", success: true });
        await tx.withTransaction(async () => {
          // unreachable
        });
      })
    ).rejects.toThrow(/does not support nesting/);

    // Outer transaction was rolled back as a result of the nested-call error.
    expect(await storage.get({ name: "outer", type: "x" })).toBeUndefined();
  });

  it("defers put events until COMMIT and discards them on ROLLBACK", async () => {
    const storage = await makeStorage();
    const observed: string[] = [];
    storage.on("put", (entity) => observed.push(entity.name));

    await storage.withTransaction(async (tx) => {
      await tx.put({ name: "committed", type: "x", option: "v", success: true });
      // No events should have been observed yet
      expect(observed).toEqual([]);
    });
    expect(observed).toEqual(["committed"]);

    observed.length = 0;

    await expect(
      storage.withTransaction(async (tx) => {
        await tx.put({ name: "doomed", type: "x", option: "v", success: true });
        throw new Error("rollback");
      })
    ).rejects.toThrow("rollback");

    // The doomed put should never have been observed by listeners.
    expect(observed).toEqual([]);
  });

  it("serializes external put() calls behind a running withTransaction (rollback case)", async () => {
    // The concurrency contract: while withTransaction is awaiting its callback,
    // an unrelated `storage.put()` invoked from outside `fn` must NOT slip into
    // the open transaction. The mutex enforces this — the external put queues
    // until COMMIT/ROLLBACK releases the lock.
    const storage = await makeStorage();

    let releaseInner: () => void = () => {};
    const innerCanFinish = new Promise<void>((resolve) => {
      releaseInner = resolve;
    });

    const txPromise = storage.withTransaction(async (tx) => {
      await tx.put({ name: "tx-row", type: "x", option: "tx", success: true });
      // Hold the transaction open until the external caller has been queued.
      await innerCanFinish;
      throw new Error("rollback");
    });

    // Yield enough microtasks for the external put() to observe withTransaction's mutex hold.
    await Promise.resolve();
    await Promise.resolve();

    const externalPut = storage.put({
      name: "external-row",
      type: "x",
      option: "external",
      success: true,
    });

    // Let the inner callback throw, triggering ROLLBACK.
    releaseInner();
    await expect(txPromise).rejects.toThrow("rollback");

    // External put runs *after* ROLLBACK and is its own committed write.
    await externalPut;

    // tx-row was rolled back, external-row was committed independently.
    expect(await storage.get({ name: "tx-row", type: "x" })).toBeUndefined();
    const ext = await storage.get({ name: "external-row", type: "x" });
    expect(ext?.option).toEqual("external");
  });
});

describe("SqliteTabularStorage regressions", () => {
  const JunctionSchema = {
    type: "object",
    properties: { a: { type: "string" }, b: { type: "string" } },
    required: ["a", "b"],
    additionalProperties: false,
  } as const satisfies DataPortSchemaObject;

  it("putBulk re-put of an existing row on an all-primary-key table is an upsert, not an error", async () => {
    const storage = new SqliteTabularStorage<typeof JunctionSchema, readonly ["a", "b"]>(
      ":memory:",
      `junction_bulk_${uuid4().replace(/-/g, "_")}`,
      JunctionSchema,
      ["a", "b"] as const
    );
    await storage.setupDatabase();
    await storage.putBulk([{ a: "x", b: "y" }]);
    const again = await storage.putBulk([{ a: "x", b: "y" }]);
    expect(again).toEqual([{ a: "x", b: "y" }]);
    expect(await storage.size()).toBe(1);
  });
});

describe("SqliteTabularStorage putBulk across shared connection", () => {
  const SharedSchema = {
    type: "object",
    properties: {
      id: { type: "integer" },
      val: { type: "string" },
    },
    required: ["id", "val"],
    additionalProperties: false,
  } as const satisfies DataPortSchemaObject;

  async function makeTwoOnSharedConnection() {
    await Sqlite.init();
    const db = new Sqlite.Database(":memory:");
    const tableA = `A_${uuid4().replace(/-/g, "_")}`;
    const tableB = `B_${uuid4().replace(/-/g, "_")}`;
    const repoA = new SqliteTabularStorage<typeof SharedSchema, readonly ["id"]>(
      db,
      tableA,
      SharedSchema,
      ["id"] as const
    );
    const repoB = new SqliteTabularStorage<typeof SharedSchema, readonly ["id"]>(
      db,
      tableB,
      SharedSchema,
      ["id"] as const
    );
    await repoA.setupDatabase();
    await repoB.setupDatabase();
    return { db, repoA, repoB };
  }

  it("sibling putBulk survives when the other rolls back on the shared connection", async () => {
    const { repoA, repoB } = await makeTwoOnSharedConnection();

    // Multi-chunk batch (SQLite bulk dialect chunks by 900 params ÷ per-row
    // params — with 2 columns per row, 2000 rows crosses at least 4 chunks
    // and drops microtask yields between each chunk).
    const largeBatch = Array.from({ length: 2000 }, (_, i) => ({ id: i, val: `a${i}` }));
    const smallBatch = [
      { id: 10001, val: "b1" },
      { id: 10002, val: "b2" },
      { id: 10003, val: "b3" },
    ];

    // Force A to throw AFTER its BEGIN but BEFORE its own writes commit — the
    // spy replaces the shared runBulkPut engine, so `_putBulkInternal`'s BEGIN
    // has already executed on the connection when it rejects.
    const runBulkPutSpy = vi
      .spyOn(
        repoA as unknown as { runBulkPut: (...a: unknown[]) => Promise<unknown> },
        "runBulkPut"
      )
      .mockImplementation(async () => {
        // Yield a microtask so a sibling storage on the same connection has a
        // chance to slip in between A's BEGIN and A's throw (which is the very
        // window the connection-mutex fix has to close).
        await Promise.resolve();
        await Promise.resolve();
        throw new Error("boom-A");
      });

    try {
      const [aResult, bResult] = await Promise.allSettled([
        repoA.putBulk(largeBatch),
        repoB.putBulk(smallBatch),
      ]);

      expect(aResult.status).toBe("rejected");
      if (aResult.status === "rejected") {
        expect((aResult.reason as Error).message).toContain("boom-A");
      }
      expect(bResult.status).toBe("fulfilled");

      // The invariant: without the connection-scoped lock, B's writes would
      // execute inside A's open transaction and vanish when A rolls back. The
      // fix serializes A's BEGIN..ROLLBACK bracket against B, so B's own
      // transaction commits independently and its rows survive.
      expect(await repoB.size()).toBe(smallBatch.length);
      expect(await repoA.size()).toBe(0);
    } finally {
      runBulkPutSpy.mockRestore();
    }
  });

  it("does not emit put events for rows that were rolled back on the shared connection", async () => {
    const { repoA, repoB } = await makeTwoOnSharedConnection();

    const aPuts: Array<{ id: number; val: string }> = [];
    const bPuts: Array<{ id: number; val: string }> = [];
    repoA.on("put", (entity) => aPuts.push(entity));
    repoB.on("put", (entity) => bPuts.push(entity));

    const largeBatch = Array.from({ length: 2000 }, (_, i) => ({ id: i, val: `a${i}` }));
    const smallBatch = [
      { id: 20001, val: "b1" },
      { id: 20002, val: "b2" },
    ];

    const runBulkPutSpy = vi
      .spyOn(
        repoA as unknown as { runBulkPut: (...a: unknown[]) => Promise<unknown> },
        "runBulkPut"
      )
      .mockImplementation(async () => {
        await Promise.resolve();
        await Promise.resolve();
        throw new Error("boom-A");
      });

    try {
      await Promise.allSettled([repoA.putBulk(largeBatch), repoB.putBulk(smallBatch)]);
    } finally {
      runBulkPutSpy.mockRestore();
    }

    // A rolled back — no put events on A. (putBulk's catch path emits
    // `rollback`, not `put`.)
    expect(aPuts).toHaveLength(0);

    // B's put events must match the rows actually persisted. Without the
    // connection lock, B would emit put events for rows that were then
    // silently rolled back with A, breaking this invariant.
    const surviving = new Set((await repoB.getAll())?.map((r) => (r as { id: number }).id) ?? []);
    for (const emitted of bPuts) {
      expect(surviving.has(emitted.id)).toBe(true);
    }
    expect(bPuts.length).toBe(surviving.size);
  });
});
