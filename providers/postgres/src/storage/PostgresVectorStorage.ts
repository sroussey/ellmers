import type { Pool } from "@workglow/postgres/storage";
import type {
  AutoGeneratedKeys,
  InsertEntity,
  IVectorStorage,
  VectorDistanceMetric,
  VectorIndexOptions,
  VectorSearchOptions,
} from "@workglow/storage";
import {
  assertVectorShape,
  emitSimilaritySearch,
  getMetadataProperty,
  getVectorProperty,
  matchesFilter,
  PostgresDialect,
  StorageValidationError,
  validateVectorEntities,
} from "@workglow/storage";
import type {
  DataPortSchemaObject,
  FromSchema,
  TypedArray,
  TypedArrayConstructor,
  TypedArraySchemaOptions,
} from "@workglow/util/schema";
import { cosineSimilarity } from "@workglow/util/schema";
import { PostgresTabularStorage } from "./PostgresTabularStorage";

/**
 * PostgreSQL vector repository implementation using pgvector extension.
 * Extends PostgresTabularStorage for storage.
 * Provides efficient vector similarity search with native database support.
 *
 * Requirements:
 * - PostgreSQL database with pgvector extension installed
 * - CREATE EXTENSION vector;
 *
 * @template Metadata - The metadata type
 * @template VectorCtor - Constructor for stored vectors (default {@link typeof Float32Array})
 */
/**
 * Regex for validating metadata filter keys to prevent SQL injection.
 * Only allows alphanumeric characters and underscores, starting with a letter or underscore.
 */
const SAFE_IDENTIFIER_RE = /^[a-z_]\w*$/i;

export class PostgresVectorStorage<
  Schema extends DataPortSchemaObject,
  PrimaryKeyNames extends ReadonlyArray<keyof Schema["properties"]>,
  Metadata extends Record<string, unknown> = Record<string, unknown>,
  Entity = FromSchema<Schema, TypedArraySchemaOptions>,
  InsertType extends InsertEntity<Entity, AutoGeneratedKeys<Schema>> = InsertEntity<
    Entity,
    AutoGeneratedKeys<Schema>
  >,
>
  extends PostgresTabularStorage<Schema, PrimaryKeyNames, Entity>
  implements IVectorStorage<Metadata, Schema, Entity, PrimaryKeyNames>
{
  private vectorDimensions: number;
  private readonly vectorCtor: TypedArrayConstructor;
  private vectorPropertyName: keyof Entity;
  private metadataPropertyName: keyof Entity | undefined;
  private readonly indexOptions: VectorIndexOptions;

  /**
   * Creates a new PostgreSQL vector repository
   * @param db - PostgreSQL connection pool
   * @param table - The name of the table to use for storage
   * @param schema - The schema definition for the entity
   * @param primaryKeyNames - Array of property names that form the primary key
   * @param indexes - Array of columns or column arrays to make searchable
   * @param dimensions - The number of dimensions of the vector
   * @param vectorCtor - TypedArray constructor used when hydrating vectors from SQL text (e.g. {@link Float32Array})
   * @param indexOptions - Tuning for the pgvector index (HNSW vs IVFFlat,
   *                       distance metric, m / efConstruction / lists / probes).
   *                       See {@link VectorIndexOptions} for the recall/latency
   *                       trade-offs. Defaults to HNSW with cosine distance and
   *                       pgvector's built-in `m=16`, `efConstruction=64` defaults.
   */
  constructor(
    db: Pool,
    table: string,
    schema: Schema,
    primaryKeyNames: PrimaryKeyNames,
    indexes: readonly (keyof NoInfer<Entity> | readonly (keyof NoInfer<Entity>)[])[] = [],
    dimensions: number,
    vectorCtor: TypedArrayConstructor = Float32Array,
    indexOptions: VectorIndexOptions = {}
  ) {
    super(db, table, schema, primaryKeyNames, indexes);

    this.vectorDimensions = dimensions;
    this.vectorCtor = vectorCtor;
    this.indexOptions = indexOptions;

    // Cache vector and metadata property names from schema
    const vectorProp = getVectorProperty(schema);
    if (!vectorProp) {
      throw new Error("Schema must have a property with type array and format TypedArray");
    }
    this.vectorPropertyName = vectorProp as keyof Entity;
    this.metadataPropertyName = getMetadataProperty(schema) as keyof Entity | undefined;
  }

  public override getVectorDimensions(): number {
    return this.vectorDimensions;
  }

  /** Exposes tuning to {@link PostgresTabularStorage.createVectorIndexes}. */
  protected override getVectorIndexOptions(): VectorIndexOptions {
    return this.indexOptions;
  }

  /** Resolved distance metric for this storage (defaults to cosine). */
  private get distance(): VectorDistanceMetric {
    return this.indexOptions.distance ?? "cosine";
  }

  /**
   * pgvector distance operators per metric:
   *   - cosine:        `<=>`  → cosine distance ∈ [0, 2]
   *   - l2 (euclidean): `<->` → L2 distance ∈ [0, ∞)
   *   - ip (inner):     `<#>` → negative inner product (pgvector negates so
   *                      smaller = "more similar", matching the other ops)
   */
  private get distanceOperator(): string {
    switch (this.distance) {
      case "l2":
        return "<->";
      case "ip":
        return "<#>";
      default:
        return "<=>";
    }
  }

  /**
   * SQL fragment that converts the raw distance from {@link distanceOperator}
   * into a "higher = more similar" score that the rest of the API exposes.
   *
   *   - cosine:  1 - cosine_distance       → similarity in [-1, 1]
   *   - l2:      1 / (1 + l2_distance)     → ∈ (0, 1], 1 is exact match
   *   - ip:      -(neg_inner_product)      → the actual dot product
   */
  private buildScoreExpr(vectorExpr: string, queryParam: string): string {
    const op = this.distanceOperator;
    switch (this.distance) {
      case "l2":
        return `(1.0 / (1.0 + (${vectorExpr} ${op} ${queryParam}::vector)))`;
      case "ip":
        return `(-1.0 * (${vectorExpr} ${op} ${queryParam}::vector))`;
      default:
        return `(1 - (${vectorExpr} ${op} ${queryParam}::vector))`;
    }
  }

  /**
   * Returns the `efSearch` / `probes` values configured at construction time.
   *
   * NOTE: these are query-time GUCs and must be set on the active session.
   * With a {@link Pool}, a connection is checked out per `pool.query()`, so a
   * standalone `SET hnsw.ef_search = N` issued before a SELECT lands on a
   * different client and has no effect. To apply them, callers should run
   * search queries against a single checked-out client (using `pool.connect()`)
   * inside a transaction with `SET LOCAL`, or set them at the role/database
   * level via `ALTER ROLE ... SET hnsw.ef_search = N`.
   */
  public getQueryTuning(): { efSearch?: number; probes?: number } {
    return {
      efSearch: this.indexOptions.hnsw?.efSearch,
      probes: this.indexOptions.ivfflat?.probes,
    };
  }

  /**
   * Validate every entity's vector before delegating to the tabular upsert.
   * Without this, a malformed vector reaches the pgvector text encoder and the
   * driver rejects it with an opaque round-trip error.
   */
  public override async put(entity: InsertType): Promise<Entity> {
    validateVectorEntities(
      [entity as Record<string, unknown>],
      this.vectorPropertyName as string,
      this.vectorDimensions
    );
    return super.put(entity);
  }

  public override async putBulk(entities: InsertType[]): Promise<Entity[]> {
    validateVectorEntities(
      entities as ReadonlyArray<Record<string, unknown>>,
      this.vectorPropertyName as string,
      this.vectorDimensions
    );
    return super.putBulk(entities);
  }

  public async similaritySearch(
    query: TypedArray,
    options: VectorSearchOptions<Metadata> = {}
  ): Promise<Array<Entity & { score: number }>> {
    // Bypass the generic catch below so a wrong-dim / non-finite query throws
    // a typed validation error instead of silently falling back to in-memory
    // cosine search (which would return garbage for the caller's intent).
    assertVectorShape(query, this.vectorDimensions, "query");

    const { topK = 10, filter, scoreThreshold = 0 } = options;

    try {
      // Try native pgvector search first
      const queryVector = `[${Array.from(query).join(",")}]`;
      // Use the raw column name for object-property lookup on result rows,
      // and a quoted form for splicing into SQL identifiers (handles reserved
      // words, mixed case, and any caller-supplied schema).
      const vectorColRaw = String(this.vectorPropertyName);
      const vectorCol = PostgresDialect.quoteId(vectorColRaw);
      const metadataColRaw = this.metadataPropertyName ? String(this.metadataPropertyName) : null;
      const metadataCol = metadataColRaw ? PostgresDialect.quoteId(metadataColRaw) : null;
      const distOp = this.distanceOperator;
      const scoreExpr = this.buildScoreExpr(vectorCol, "$1");

      // Cast the vector to text in the main query so we can parse it off each
      // row directly — avoids an N+1 per-result round-trip to re-fetch vectors.
      let sql = `
        SELECT
          *,
          ${vectorCol}::text as "_vector_text",
          ${scoreExpr} as score
        FROM "${this.table}"
      `;

      const params: any[] = [queryVector];
      let paramIndex = 2;
      // Track whether we've actually emitted a WHERE — `filter` alone isn't
      // sufficient because it can be truthy yet contribute zero predicates
      // (empty object, or no metadata column to apply it against).
      let hasWhere = false;

      if (filter && Object.keys(filter).length > 0 && metadataCol) {
        const conditions: string[] = [];
        for (const [key, value] of Object.entries(filter)) {
          if (!SAFE_IDENTIFIER_RE.test(key)) {
            throw new StorageValidationError(
              `Invalid metadata filter key: "${key}". Keys must match /^[a-zA-Z_][a-zA-Z0-9_]*$/.`
            );
          }
          // The JSON key inside `->>` is already validated above; we still
          // need to quote the column identifier itself to handle non-trivial
          // metadata column names.
          conditions.push(`${metadataCol}->>'${key}' = $${paramIndex}`);
          params.push(String(value));
          paramIndex++;
        }
        if (conditions.length > 0) {
          sql += ` WHERE ${conditions.join(" AND ")}`;
          hasWhere = true;
        }
      }

      // Always emit the score threshold predicate so behaviour matches the
      // in-memory fallback (`score >= scoreThreshold`) for every metric and
      // every threshold value (including 0 / negative).
      sql += hasWhere ? " AND" : " WHERE";
      sql += ` ${scoreExpr} >= $${paramIndex}`;
      params.push(scoreThreshold);
      paramIndex++;

      // ORDER BY uses the raw distance (smaller = closer) so the configured
      // pgvector index can serve the query directly.
      sql += ` ORDER BY ${vectorCol} ${distOp} $1::vector LIMIT $${paramIndex}`;
      params.push(topK);

      const result = await this.db.query(sql, params);

      const results: Array<Entity & { score: number }> = [];
      for (const row of result.rows) {
        // `_vector_text` is the text-cast vector from the SELECT above; drop it
        // from the spread and parse it into the typed vector property.
        const { _vector_text, ...rest } = row as Record<string, unknown> & {
          _vector_text?: string;
        };
        const vectorArray = JSON.parse((_vector_text as string) || "[]");

        results.push({
          ...rest,
          [this.vectorPropertyName]: new this.vectorCtor(vectorArray),
          score: parseFloat((rest as { score: unknown }).score as string),
        } as Entity & { score: number });
      }

      return emitSimilaritySearch(this.events, query, results);
    } catch (error) {
      if (error instanceof StorageValidationError) {
        throw error; // Don't swallow validation errors
      }
      // Fall back to in-memory similarity calculation if pgvector is not available
      console.error("pgvector query failed, falling back to in-memory search:", error);
      return this.searchFallback(query, options);
    }
  }

  /**
   * Throws if the configured distance metric isn't cosine. The in-memory
   * fallback paths below only know how to compute cosine similarity; if
   * pgvector is unavailable for an `l2`/`ip` storage, falling back would
   * silently return wrong scores. Callers using non-cosine distances must
   * keep pgvector working.
   */
  private assertFallbackSupportsDistance(): void {
    if (this.distance !== "cosine") {
      throw new Error(
        `PostgresVectorStorage: pgvector is unavailable and the in-memory ` +
          `fallback only supports cosine distance (configured: "${this.distance}"). ` +
          `Install pgvector or switch the storage to cosine distance.`
      );
    }
  }

  /**
   * Fallback search using in-memory cosine similarity. Only valid for
   * `distance: "cosine"`; see {@link assertFallbackSupportsDistance}.
   */
  private async searchFallback(query: TypedArray, options: VectorSearchOptions<Metadata>) {
    this.assertFallbackSupportsDistance();
    const { topK = 10, filter, scoreThreshold = 0 } = options;
    const allRows = (await this.getAll()) || [];
    const results: Array<Entity & { score: number }> = [];

    for (const row of allRows) {
      const vector = row[this.vectorPropertyName] as TypedArray;
      const metadata = this.metadataPropertyName
        ? (row[this.metadataPropertyName] as Metadata)
        : ({} as Metadata);

      if (filter && !matchesFilter(metadata, filter)) {
        continue;
      }

      const score = cosineSimilarity(query, vector);

      if (score >= scoreThreshold) {
        results.push({ ...row, score } as Entity & { score: number });
      }
    }

    results.sort((a, b) => b.score - a.score);
    const topResults = results.slice(0, topK);

    return emitSimilaritySearch(this.events, query, topResults);
  }
}
