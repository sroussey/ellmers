import type { SupabaseClient } from "@supabase/supabase-js";
import type {
  CoveringIndexQueryOptions,
  DeleteSearchCriteria,
  InsertEntity,
  IVectorStorage,
  Page,
  PageRequest,
  QueryOptions,
  SearchCriteria,
  SimplifyPrimaryKey,
  VectorSearchOptions,
} from "@workglow/storage";
import {
  AutoGeneratedKeys,
  getMetadataProperty,
  getVectorProperty,
  StorageValidationError,
} from "@workglow/storage";
import type {
  DataPortSchemaObject,
  FromSchema,
  TypedArray,
  TypedArrayConstructor,
  TypedArraySchemaOptions,
} from "@workglow/util/schema";
import { SupabaseTabularStorage } from "./SupabaseTabularStorage";

/**
 * Regex for validating metadata filter keys to prevent SQL/filter injection.
 * Only allows alphanumeric characters and underscores, starting with a letter
 * or underscore. Mirrors {@link PostgresVectorStorage}.
 */
const SAFE_IDENTIFIER_RE = /^[a-zA-Z_][a-zA-Z0-9_]*$/;

/**
 * A generic equality scope a vector store can be bound to: a map of column
 * name to value. When set, every read and write is constrained to these
 * columns (writes stamp them, reads filter on them, and the `match_<table>`
 * RPC receives them as `p_scope`). The column names carry no meaning here —
 * the caller picks them (e.g. an application might bind a tenant/project key).
 */
export type VectorScope = Record<string, string>;

/**
 * Supabase-backed vector repository. Extends {@link SupabaseTabularStorage}
 * for row storage and delegates similarity search to a server-side
 * `match_<table>` RPC (pgvector).
 *
 * The RPC contract is generic; the consumer owns the table and the function
 * via a migration. The expected signature is:
 *
 * ```sql
 * match_<table>(
 *   query_embedding vector,   -- the search vector
 *   match_count     int,      -- LIMIT
 *   score_threshold float,    -- optional minimum score (NULL = no minimum)
 *   p_scope         jsonb,    -- equality scope (the bound {@link VectorScope})
 *   p_filter        jsonb     -- metadata containment filter
 * ) returns setof <table-row + score float>
 * ```
 *
 * The function decides how to apply `p_scope` (which scope columns exist is the
 * consumer's concern) and must order by vector distance and return a `score`.
 *
 * Binding a {@link VectorScope} via {@link withScope} is optional. When bound,
 * scope columns are stamped onto writes from the resolved scope rather than
 * from client input, and every read/delete is narrowed to the scope. When
 * unbound, the store behaves as a plain table-wide vector store.
 *
 * @template Schema - The schema definition for the entity
 * @template PrimaryKeyNames - Array of property names that form the primary key
 * @template Metadata - The metadata type used for filters
 */
export class SupabaseVectorStorage<
  Schema extends DataPortSchemaObject,
  PrimaryKeyNames extends ReadonlyArray<keyof Schema["properties"]>,
  Metadata extends Record<string, unknown> = Record<string, unknown>,
  Entity = FromSchema<Schema, TypedArraySchemaOptions>,
  InsertType extends InsertEntity<Entity, AutoGeneratedKeys<Schema>> = InsertEntity<
    Entity,
    AutoGeneratedKeys<Schema>
  >,
>
  extends SupabaseTabularStorage<Schema, PrimaryKeyNames, Entity>
  implements IVectorStorage<Metadata, Schema, Entity, PrimaryKeyNames>
{
  public readonly tableName: string;
  private readonly vectorDimensions: number;
  private readonly vectorCtor: TypedArrayConstructor;
  private readonly vectorPropertyName: keyof Entity;
  private readonly metadataPropertyName: keyof Entity | undefined;
  // Captured constructor args so withScope can build a real, independent
  // instance rather than a prototype clone that would alias base mutable
  // state (realtime channel, event listeners).
  private readonly initSchema: Schema;
  private readonly initPrimaryKeyNames: PrimaryKeyNames;
  private readonly initIndexes: readonly (
    | keyof NoInfer<Entity>
    | readonly (keyof NoInfer<Entity>)[]
  )[];
  private scope: VectorScope | undefined;

  /**
   * @param client - Supabase client instance
   * @param table - The name of the table (and the suffix of its `match_<table>` RPC)
   * @param schema - The schema definition for the entity
   * @param primaryKeyNames - Array of property names that form the primary key
   * @param indexes - Columns or column arrays to make searchable
   * @param dimensions - The number of dimensions of the vector
   * @param vectorCtor - TypedArray constructor used when hydrating vectors (default {@link Float32Array})
   */
  constructor(
    client: SupabaseClient,
    table: string,
    schema: Schema,
    primaryKeyNames: PrimaryKeyNames,
    indexes: readonly (keyof NoInfer<Entity> | readonly (keyof NoInfer<Entity>)[])[] = [],
    dimensions: number,
    vectorCtor: TypedArrayConstructor = Float32Array
  ) {
    super(client, table, schema, primaryKeyNames, indexes);

    this.tableName = table;
    this.vectorDimensions = dimensions;
    this.vectorCtor = vectorCtor;
    this.initSchema = schema;
    this.initPrimaryKeyNames = primaryKeyNames;
    this.initIndexes = indexes;

    const vectorProp = getVectorProperty(schema);
    if (!vectorProp) {
      throw new Error("Schema must have a property with type array and format TypedArray");
    }
    this.vectorPropertyName = vectorProp as keyof Entity;
    this.metadataPropertyName = getMetadataProperty(schema) as keyof Entity | undefined;
  }

  public getVectorDimensions(): number {
    return this.vectorDimensions;
  }

  /**
   * Returns an independent store instance bound to the given scope. A fresh
   * instance (not a prototype clone) is constructed so scoped views do not
   * alias the base storage's mutable state (realtime channel, event listeners)
   * while still sharing the same underlying client connection.
   */
  public withScope(scope: VectorScope): this {
    const Ctor = this.constructor as new (
      client: SupabaseClient,
      table: string,
      schema: Schema,
      primaryKeyNames: PrimaryKeyNames,
      indexes: readonly (keyof NoInfer<Entity> | readonly (keyof NoInfer<Entity>)[])[],
      dimensions: number,
      vectorCtor: TypedArrayConstructor
    ) => this;
    const clone = new Ctor(
      this.client,
      this.tableName,
      this.initSchema,
      this.initPrimaryKeyNames,
      this.initIndexes,
      this.vectorDimensions,
      this.vectorCtor
    );
    clone.scope = { ...scope };
    return clone;
  }

  /**
   * Serialize the vector TypedArray to pgvector text (`[a,b,c]`) and, when a
   * scope is bound, stamp the scope columns. The base tabular upsert forwards
   * values to the driver unchanged, and PGlite/pgvector accept the text form
   * for a `vector` column — a raw TypedArray would be rejected. Scope columns
   * always come from the resolved scope, never from client-supplied input.
   */
  private prepareForWrite(entity: InsertType): InsertType {
    const record = { ...(entity as Record<string, unknown>) };

    record[this.vectorPropertyName as string] = this.toPgVectorText(
      record[this.vectorPropertyName as string]
    );
    if (this.metadataPropertyName !== undefined) {
      const metaCol = this.metadataPropertyName as string;
      if (record[metaCol] === undefined || record[metaCol] === null) {
        record[metaCol] = {};
      }
    }
    if (this.scope) {
      Object.assign(record, this.scope);
    }

    return record as InsertType;
  }

  private toPgVectorText(value: unknown): string {
    const arr = value as ArrayLike<number>;
    return `[${Array.from(arr).join(",")}]`;
  }

  public override async put(entity: InsertType): Promise<Entity> {
    const saved = await super.put(this.prepareForWrite(entity));
    return this.restampVector(saved, entity);
  }

  public override async putBulk(entities: InsertType[]): Promise<Entity[]> {
    if (entities.length === 0) return [];
    const saved = await super.putBulk(entities.map((e) => this.prepareForWrite(e)));
    return saved.map((row, i) => this.restampVector(row, entities[i]));
  }

  /**
   * Returns the hydrated DB row (preserving any server-generated columns) with
   * the vector column restored to the caller's TypedArray — the persisted form
   * is pgvector text, but callers expect the original typed vector back.
   */
  private restampVector(saved: Entity, input: InsertType): Entity {
    const out = { ...(saved as Record<string, unknown>) };
    out[this.vectorPropertyName as string] = (input as Record<string, unknown>)[
      this.vectorPropertyName as string
    ];
    return out as Entity;
  }

  public async similaritySearch(
    query: TypedArray,
    options: VectorSearchOptions<Metadata> = {}
  ): Promise<Array<Entity & { score: number }>> {
    const { topK = 10, filter = {} as Partial<Metadata>, scoreThreshold = 0 } = options;

    for (const key of Object.keys(filter)) {
      if (!SAFE_IDENTIFIER_RE.test(key)) {
        throw new StorageValidationError(
          `Invalid metadata filter key: "${key}". Keys must match /^[a-zA-Z_][a-zA-Z0-9_]*$/.`
        );
      }
    }

    // The param-object key order matches the SQL function's parameter order;
    // the PGlite test mock routes RPC params positionally, so this ordering is
    // load-bearing and must not be reordered.
    const { data, error } = await this.client.rpc(`match_${this.tableName}`, {
      query_embedding: `[${Array.from(query).join(",")}]`,
      match_count: topK,
      score_threshold: scoreThreshold,
      p_scope: this.scope ?? {},
      p_filter: filter,
    });

    if (error) throw error;

    const rows = (data ?? []) as Array<Record<string, unknown>>;
    const vectorCol = this.vectorPropertyName as string;

    return rows.map((row) => {
      const hydrated = { ...row } as Record<string, unknown>;
      hydrated[vectorCol] = new this.vectorCtor(this.parseVector(row[vectorCol]));
      hydrated.score = Number(row.score);
      return hydrated as Entity & { score: number };
    });
  }

  /** Parse a pgvector value into a plain number array; accepts text or array forms. */
  private parseVector(value: unknown): number[] {
    if (Array.isArray(value)) return value as number[];
    if (typeof value === "string") {
      const trimmed = value.trim();
      if (trimmed === "" || trimmed === "[]") return [];
      return trimmed
        .replace(/^\[/, "")
        .replace(/\]$/, "")
        .split(",")
        .map((s) => Number(s));
    }
    return [];
  }

  // ---- Scope-enforcing overrides -------------------------------------------
  // The inherited tabular methods operate table-wide. When a scope is bound,
  // every access must stay within it, so the scope columns are narrowed onto
  // each inherited read/delete here (scope values win over caller criteria).
  // Without this a single scope's `getAll`/`deleteAll` would read or delete
  // every row the connection can see. With no scope bound, each method falls
  // through to the plain table-wide base behavior.

  private mergeScope<T extends Record<string, unknown>>(base: T): T {
    return this.scope ? { ...base, ...this.scope } : base;
  }

  private scopeCriteria(): SearchCriteria<Entity> {
    return (this.scope ?? {}) as SearchCriteria<Entity>;
  }

  public override async get(
    key: SimplifyPrimaryKey<Entity, PrimaryKeyNames>
  ): Promise<Entity | undefined> {
    return super.get(this.mergeScope(key as Record<string, unknown>) as typeof key);
  }

  public override async delete(
    value: SimplifyPrimaryKey<Entity, PrimaryKeyNames> | Entity
  ): Promise<void> {
    return super.delete(this.mergeScope(value as Record<string, unknown>) as typeof value);
  }

  public override async getAll(options?: QueryOptions<Entity>): Promise<Entity[] | undefined> {
    if (!this.scope) return super.getAll(options);
    return super.query(this.scopeCriteria(), options);
  }

  public override async deleteAll(): Promise<void> {
    if (!this.scope) return super.deleteAll();
    await super.deleteSearch(this.scopeCriteria() as DeleteSearchCriteria<Entity>);
  }

  public override async size(): Promise<number> {
    if (!this.scope) return super.size();
    return super.count(this.scopeCriteria());
  }

  public override async count(criteria?: SearchCriteria<Entity>): Promise<number> {
    if (!this.scope) return super.count(criteria);
    return super.count(
      this.mergeScope((criteria ?? {}) as Record<string, unknown>) as SearchCriteria<Entity>
    );
  }

  public override async query(
    criteria: SearchCriteria<Entity>,
    options?: QueryOptions<Entity>
  ): Promise<Entity[] | undefined> {
    return super.query(
      this.mergeScope(criteria as Record<string, unknown>) as SearchCriteria<Entity>,
      options
    );
  }

  public override async deleteSearch(criteria: DeleteSearchCriteria<Entity>): Promise<void> {
    await super.deleteSearch(
      this.mergeScope(criteria as Record<string, unknown>) as DeleteSearchCriteria<Entity>
    );
  }

  public override async getOffsetPage(
    offset: number,
    limit: number
  ): Promise<Entity[] | undefined> {
    if (!this.scope) return super.getOffsetPage(offset, limit);
    return super.query(this.scopeCriteria(), { offset, limit });
  }

  public override async getPage(request: PageRequest<Entity> = {}): Promise<Page<Entity>> {
    if (!this.scope) return super.getPage(request);
    return super.queryPage(this.scopeCriteria(), request);
  }

  public override async queryPage(
    criteria: SearchCriteria<Entity>,
    request: PageRequest<Entity> = {}
  ): Promise<Page<Entity>> {
    return super.queryPage(
      this.mergeScope(criteria as Record<string, unknown>) as SearchCriteria<Entity>,
      request
    );
  }

  public override async queryIndex<K extends keyof Entity & string>(
    criteria: SearchCriteria<Entity>,
    options: CoveringIndexQueryOptions<Entity, K>
  ): Promise<Pick<Entity, K>[]> {
    return super.queryIndex(
      this.mergeScope(criteria as Record<string, unknown>) as SearchCriteria<Entity>,
      options
    );
  }
}
